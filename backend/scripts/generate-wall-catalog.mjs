import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const backendRoot = resolve(here, '..')
const repoRoot = resolve(backendRoot, '..')
const configPath = resolve(backendRoot, 'walls.json')
const outputPath = resolve(backendRoot, 'src/generated/wallCatalog.ts')

const wallConfigs = JSON.parse(await readFile(configPath, 'utf8'))
if (!Array.isArray(wallConfigs) || wallConfigs.length === 0) {
  throw new Error('backend/walls.json must contain at least one wall version')
}

const generated = []
for (const config of wallConfigs) {
  const required = ['gymId', 'wallId', 'wallVersionId', 'displayName', 'holdSource']
  for (const key of required) {
    if (typeof config[key] !== 'string' || !config[key]) throw new Error(`Invalid wall config: missing ${key}`)
  }

  const holdPath = resolve(repoRoot, config.holdSource)
  const holds = JSON.parse(await readFile(holdPath, 'utf8'))
  if (!Array.isArray(holds)) throw new Error(`${config.holdSource} must be an array`)

  const ids = holds.map((hold) => hold?.id)
  if (ids.some((id) => typeof id !== 'string' || !id)) {
    throw new Error(`${config.holdSource} contains a hold without a valid id`)
  }
  const unique = new Set(ids)
  if (unique.size !== ids.length) throw new Error(`${config.holdSource} contains duplicate hold ids`)

  generated.push({
    gymId: config.gymId,
    wallId: config.wallId,
    wallVersionId: config.wallVersionId,
    displayName: config.displayName,
    active: config.active !== false,
    holdIds: ids,
  })
}

const source = `// Generated by backend/scripts/generate-wall-catalog.mjs. Do not edit by hand.\n` +
  `export const wallCatalog = ${JSON.stringify(generated, null, 2)} as const\n`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, source)
console.log(`Generated ${outputPath} with ${generated.reduce((sum, wall) => sum + wall.holdIds.length, 0)} hold ids`)
