const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const fs = require('node:fs'), assert = require('node:assert/strict')
const base = process.env.APP_URL || 'http://127.0.0.1:8792'

async function main() {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium', args:['--no-sandbox']})
  try {
    const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
    const page = await context.newPage(), errors = [], predictions = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => {if(request.method()==='POST' && request.url().endsWith('/predict'))predictions.push(request.url())})
    if(process.env.AUTH_KEY_FILE)await page.goto(base+'/auth?key='+encodeURIComponent(fs.readFileSync(process.env.AUTH_KEY_FILE,'utf8').trim()))
    const open = async () => {
      await page.getByRole('button',{name:'Open local server scan',exact:true}).click()
      await page.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})
    }
    const state = () => page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(key => key.startsWith('stoneham-wall-review-v1:')))))
    await page.goto(base+'/?annotate=1&review=1');await open()
    const initial = await state()
    assert.equal(initial.session.candidateVersion,'2026-11-v7-seam-trial')
    assert.equal(initial.session.registeredImageSha256,'6fb57bee42af9b5b51283d79502968466cf7d25eaf0f5a6a64b3c92c22e4e72b')
    assert.equal(initial.entries.length,797);assert.equal(initial.reviewRevision,0)
    assert(initial.entries.every(entry => entry.status==='inherited-unreviewed'))
    const snapshot = JSON.parse(fs.readFileSync('reviews/2026-11-v6-highres/confirmed-geometry.json'))
    assert.deepEqual(initial.entries.map(entry => entry.hold),snapshot.holds)
    await page.getByLabel('Reviewer name',{exact:true}).fill('Final review smoke test')
    const next = page.getByRole('button',{name:'Next pending hold',exact:true})
    await next.click()
    assert.equal(predictions.length,0,'Final recheck must initially preserve the hand-reviewed outline')
    const id = await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
    await page.getByRole('button',{name:'Confirm',exact:true}).click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(key => key.startsWith('stoneham-wall-review-v1:')))).reviewRevision===1)
    assert.deepEqual((await state()).entries.find(entry => entry.hold.id===id).hold,snapshot.holds.find(hold => hold.id===id))
    await page.reload();await open();assert.equal((await state()).reviewRevision,1)
    await page.getByText('Session, reviewer & backups',{exact:true}).click()
    const download = page.waitForEvent('download');await page.getByRole('button',{name:'Export progress',exact:true}).click()
    const exported = JSON.parse(fs.readFileSync(await (await download).path()))
    assert.equal(exported.reviewRevision,1);assert.equal(exported.entries.length,797)
    await page.getByLabel('Resume progress',{exact:true}).setInputFiles('reviews/2026-11-v6-highres/review-progress-r826.json')
    await page.getByRole('alert').filter({hasText:'Wrong scan/image identity'}).waitFor()
    assert.equal((await state()).reviewRevision,1)
    await next.click()
    const responsePromise=page.waitForResponse(response => response.url().endsWith('/predict') && response.request().method()==='POST',{timeout:120000})
    await page.getByRole('button',{name:'Generate mask',exact:true}).click()
    const response=await responsePromise;assert.equal(response.status(),200)
    const prediction=await response.json();assert(prediction.candidates.length>0)
    assert.equal((await state()).reviewRevision,1,'Generating a mask must not confirm it')
    fs.mkdirSync('artifacts',{recursive:true})
    await page.screenshot({path:'artifacts/v7-final-review-mobile.png'})
    assert.deepEqual(errors,[])
    console.log('PASS: 797 exact saved outlines, distinct unapproved v7 session, no automatic inference, confirm/reload/export, old checkpoint rejected, live SAM2 mask without approval.')
  } finally { await browser.close() }
}
main().catch(error => {console.error(error);process.exitCode=1})
