const {readReviewState,waitForReviewRevision}=require('./review-test-storage.cjs')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const fs=require('node:fs'), assert=require('node:assert/strict')
const base=process.env.APP_URL||'http://127.0.0.1:8790'
const expectedProposals=Number(process.env.EXPECTED_PROPOSALS||639)
const expectedVersion=process.env.EXPECTED_VERSION||'2026-11-v5'
async function main(){
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox'],proxy:process.env.BROWSER_PROXY?{server:process.env.BROWSER_PROXY}:undefined})
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true})
  const page=await context.newPage(),errors=[],writes=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(r.method()==='POST')writes.push(new URL(r.url()).pathname)})
  page.setDefaultTimeout(30000)
  // Optional transport for environments whose proxy CA is trusted by Node, not Chromium.
  if(process.env.BROWSER_FETCH_PROXY==='1')await page.route('https://**/*',async route=>route.fulfill({response:await route.fetch()}))
  if(process.env.AUTH_KEY_FILE)await page.goto(base+'/auth?key='+encodeURIComponent(fs.readFileSync(process.env.AUTH_KEY_FILE,'utf8').trim()))
  await page.goto(base+'/?review=1')
  const open=async()=>{await page.getByRole('button',{name:'Open local server scan',exact:true}).click();await page.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})}
  await open()
  const state=()=>readReviewState(page)
  assert.equal((await state()).entries.length,677)
  assert.equal((await state()).session.candidateVersion,expectedVersion)
  if(process.env.EXPECTED_IMAGE_SHA256)assert.equal((await state()).session.registeredImageSha256,process.env.EXPECTED_IMAGE_SHA256)
  assert.equal((await state()).reviewRevision,0)
  await page.getByRole('heading',{name:`SAM2 suggestions (${expectedProposals})`,exact:true}).waitFor()
  await page.getByText('Session, reviewer & backups',{exact:true}).click()
  await page.getByLabel('Reviewer name',{exact:true}).fill('V5 smoke')
  assert.equal(await page.getByLabel('Auto-run SAM2 on next hold',{exact:true}).isChecked(),false)
  await page.getByLabel('Auto-run SAM2 on next hold',{exact:true}).check()
  const automatic=page.waitForResponse(r=>r.url().endsWith('/api/sam2/predict'),{timeout:120000})
  await page.getByRole('button',{name:'Next pending hold',exact:true}).click()
  assert.equal((await automatic).status(),200,'next hold runs SAM2 automatically')
  const originalId=await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
  const inherited=(await state()).entries.find(e=>e.hold.id===originalId)
  await page.getByRole('button',{name:'Load SAM2 suggestion',exact:true}).click()
  assert.equal((await state()).reviewRevision,0,'loading a suggestion cannot approve it')
  assert(await page.getByRole('button',{name:'Confirm unchanged',exact:true}).isDisabled())
  await page.getByRole('button',{name:'Old wall',exact:true}).click()
  assert(await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).isDisabled())
  await page.getByRole('button',{name:'New scan',exact:true}).click()
  await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).click()
  await waitForReviewRevision(page,1)
  const revised=(await state()).entries.find(e=>e.hold.id===originalId)
  assert.equal(revised.status,'verified-refined');assert.notDeepEqual(revised.hold.polygon,inherited.hold.polygon)
  await page.getByRole('button',{name:'Next pending hold',exact:true}).click()
  await page.getByRole('button',{name:'Load SAM2 suggestion',exact:true}).click()
  const prediction=page.waitForResponse(r=>r.url().endsWith('/api/sam2/predict'),{timeout:120000})
  await page.getByRole('button',{name:'Generate mask',exact:true}).click()
  const response=await prediction;assert.equal(response.status(),200)
  const masks=await response.json();assert(masks.candidates.length>0,'real SAM2 must return an outline')
  assert(masks.candidates.every(c=>c.polygon.length>=3&&c.polygon.length<=16))
  assert.equal((await state()).reviewRevision,1,'inference does not approve geometry')
  const wrong=await page.request.post(base+'/api/sam2/predict',{data:{points:[{point:[.2,.2],label:1}],sessionId:'wrong',image_sha256:'wrong'}})
  assert.equal(wrong.status(),400)
  await page.getByRole('button',{name:'New hold / Clear',exact:true}).click()
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export progress',exact:true}).click()
  const exported=JSON.parse(fs.readFileSync(await (await download).path(),'utf8'))
  assert.equal(exported.reviewRevision,1);assert.equal(exported.publishable,false)
  await page.reload();await open();assert.equal((await state()).reviewRevision,1)
  assert.equal((await state()).entries.find(e=>e.hold.id===originalId).status,'verified-refined')
  await page.getByText('Session, reviewer & backups',{exact:true}).click()
  const bulk=page.getByRole('button',{name:/^Confirm eligible SAM2 outlines/})
  await page.getByLabel('Reviewer name',{exact:true}).fill('')
  assert(!await bulk.isDisabled(),'missing reviewer is actionable, not a silent disabled button')
  await bulk.click()
  assert(await page.getByLabel('Reviewer name',{exact:true}).evaluate(e=>document.activeElement===e))
  await page.getByRole('alert').filter({hasText:'Enter your reviewer name'}).waitFor()
  await page.getByLabel('Reviewer name',{exact:true}).fill('Bulk smoke')
  await page.getByLabel('Minimum SAM2 score',{exact:true}).fill('1')
  assert(await bulk.isDisabled(),'threshold 1 has no eligible proposals')
  await page.getByLabel('Minimum SAM2 score',{exact:true}).fill('0.95')
  const count=Number((await bulk.innerText()).match(/\((\d+)\)/)[1]);assert(count>0)
  await page.evaluate(()=>{window.originalReviewPut=IDBObjectStore.prototype.put;IDBObjectStore.prototype.put=function(...args){if(this.name==='checkpoints')throw new Error('Test quota');return window.originalReviewPut.apply(this,args)}})
  await bulk.click();await page.getByRole('alert').filter({hasText:'Batch not saved'}).waitFor()
  assert.equal((await state()).reviewRevision,1,'storage failure leaves the entire batch unchanged')
  await page.evaluate(()=>{IDBObjectStore.prototype.put=window.originalReviewPut})
  await bulk.click()
  await waitForReviewRevision(page,1+count)
  assert.equal((await state()).entries.filter(e=>e.status==='verified-refined').length,1+count)
  assert.equal(await bulk.innerText(),'Confirm eligible SAM2 outlines (0)')
  await page.reload();await open();assert.equal((await state()).reviewRevision,1+count)
  await page.getByRole('button',{name:'Fit wall',exact:true}).click()
  await page.locator('.annotation-viewport').scrollIntoViewIfNeeded()
  fs.mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/v5-review-mobile.png'})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[]);assert(writes.every(p=>p==='/api/sam2/predict'))
  console.log(`PASS: ${expectedVersion} image + ${expectedProposals} proposals, explicit refinement with old ID, compare lock, real SAM2 (${masks.elapsed_seconds.toFixed(2)}s), wrong-session rejection, checkpoint/reload, auto-run on next, threshold bulk confirmation, atomic storage failure/retry, bulk reload, mobile layout, no legacy writes.`)
 }finally{await browser.close()}
}
main().catch(e=>{console.error(String(e.stack||e).replace(/([?&]key=)[A-Za-z0-9_-]+/g,'$1[redacted]'));process.exitCode=1})
