const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const fs=require('node:fs'), assert=require('node:assert/strict')
const base=process.env.APP_URL||'http://127.0.0.1:8790'
async function main(){
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true})
  const page=await context.newPage(),errors=[],writes=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(r.method()==='POST')writes.push(new URL(r.url()).pathname)})
  page.setDefaultTimeout(30000)
  if(process.env.AUTH_KEY_FILE)await page.goto(base+'/auth?key='+encodeURIComponent(fs.readFileSync(process.env.AUTH_KEY_FILE,'utf8').trim()))
  else await page.goto(base+'/?review=1')
  const open=async()=>{await page.getByRole('button',{name:'Open local server scan',exact:true}).click();await page.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})}
  await open()
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('stoneham-wall-review-v1:')))))
  assert.equal((await state()).entries.length,677)
  assert.equal((await state()).reviewRevision,0)
  await page.getByRole('heading',{name:'SAM2 suggestions (639)',exact:true}).waitFor()
  await page.getByText('Session, reviewer & backups',{exact:true}).click()
  await page.getByLabel('Reviewer name',{exact:true}).fill('V5 smoke')
  await page.getByRole('button',{name:'Next unreviewed hold',exact:true}).click()
  const originalId=await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
  const inherited=(await state()).entries.find(e=>e.hold.id===originalId)
  await page.getByRole('button',{name:'Load SAM2 suggestion',exact:true}).click()
  assert.equal((await state()).reviewRevision,0,'loading a suggestion cannot approve it')
  assert(await page.getByRole('button',{name:'Confirm unchanged',exact:true}).isDisabled())
  await page.getByRole('button',{name:'Old wall',exact:true}).click()
  assert(await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).isDisabled())
  await page.getByRole('button',{name:'New scan',exact:true}).click()
  await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).click()
  await page.waitForFunction(()=>Object.keys(localStorage).some(k=>k.startsWith('stoneham-wall-review-v1:')&&JSON.parse(localStorage.getItem(k)).reviewRevision===1))
  const revised=(await state()).entries.find(e=>e.hold.id===originalId)
  assert.equal(revised.status,'verified-refined');assert.notDeepEqual(revised.hold.polygon,inherited.hold.polygon)
  await page.getByRole('button',{name:'Next unreviewed hold',exact:true}).click()
  await page.getByRole('button',{name:'Load SAM2 suggestion',exact:true}).click()
  const prediction=page.waitForResponse(r=>r.url().endsWith('/api/sam2/predict'),{timeout:120000})
  await page.getByRole('button',{name:'Generate mask',exact:true}).click()
  const response=await prediction;assert.equal(response.status(),200)
  const masks=await response.json();assert(masks.candidates.length>0,'real SAM2 must return an outline')
  assert(masks.candidates.every(c=>c.polygon.length>=3&&c.polygon.length<=16))
  assert.equal((await state()).reviewRevision,1,'inference does not approve geometry')
  const wrong=await page.request.post(base+'/api/sam2/predict',{data:{points:[{point:[.2,.2],label:1}],sessionId:'wrong',image_sha256:'wrong'}})
  assert.equal(wrong.status(),400)
  await page.getByRole('button',{name:'New hold / Clear',exact:true}).click()
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export progress',exact:true}).click()
  const exported=JSON.parse(fs.readFileSync(await (await download).path(),'utf8'))
  assert.equal(exported.reviewRevision,1);assert.equal(exported.publishable,false)
  await page.reload();await open();assert.equal((await state()).reviewRevision,1)
  assert.equal((await state()).entries.find(e=>e.hold.id===originalId).status,'verified-refined')
  await page.getByRole('button',{name:'Fit wall',exact:true}).click()
  await page.locator('.annotation-viewport').scrollIntoViewIfNeeded()
  fs.mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/v5-review-mobile.png'})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[]);assert(writes.every(p=>p==='/api/sam2/predict'))
  console.log(`PASS: v5 image + 639 proposals, explicit refinement with old ID, compare lock, real SAM2 (${masks.elapsed_seconds.toFixed(2)}s), wrong-session rejection, checkpoint/reload, mobile layout, no legacy writes.`)
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
