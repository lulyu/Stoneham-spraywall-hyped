const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const assert = require('node:assert/strict')
const { holds } = require('../src/data/experiments/top_left_sam2_polygons.json')
const canonical = require('../src/data/polygons/holds.json')
const canonicalIds = new Set(canonical.map(hold => hold.id))
const fs = require('node:fs')

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    page.setDefaultTimeout(5000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto(process.env.APP_URL || 'http://127.0.0.1:4173')
    await page.getByRole('heading', { name: 'Hyped@Stoneham SprayWall', exact: true }).waitFor()
    assert.equal(await page.locator('.debug-polygon').count(), 0)
    await page.getByText('Polygon debug', { exact: true }).click()
    await page.getByLabel('Show all polygons', { exact: true }).check()
    assert.equal(await page.locator('.debug-polygon').count(), canonical.length)
    await page.getByLabel('Show polygon labels', { exact: true }).check()
    assert.equal(await page.locator('.debug-polygon-label').count(), canonical.length)
    await page.getByLabel('Debug dataset', { exact: true }).selectOption('sam2')
    assert.equal(await page.locator('.debug-polygon').count(), holds.length)
    assert.equal(await page.locator('.debug-polygon-label').count(), holds.length)
    const fitted = await page.locator('.wall-stage').evaluate(element => element.style.transform)
    await page.getByRole('button', { name: 'Focus top-left crop' }).tap()
    await page.waitForFunction(previous => document.querySelector('.wall-stage').style.transform !== previous, fitted)
    fs.mkdirSync('artifacts', { recursive: true })
    await page.locator('.wall-image').evaluate(img => img.decode())
    await page.screenshot({ path: 'artifacts/sam2-top-left-ui-debug.png' })
    await page.getByRole('button', { name: 'Fit wall', exact: true }).tap()
    await page.getByRole('button', { name: '＋ Set', exact: true }).tap()
    assert.equal(await page.locator('.hold-hit-polygon').count(), canonical.length)
    await page.locator('.hold-hit-polygon').nth(0).tap()
    await page.locator('.hold-hit-polygon').nth(1).tap()
    await page.getByText('2 selected', { exact: true }).waitFor()
    await page.getByLabel('Problem name').fill('Debug overlay route test')
    await page.getByRole('button', { name: 'Save problem' }).tap()
    await page.getByText('Debug overlay route test', { exact: true }).waitFor()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('stoneham-spraywall:problems:v3')))
    assert(saved[0].holds.every(hold => canonicalIds.has(hold.holdId)))
    await page.getByLabel('Show all polygons', { exact: true }).uncheck()
    assert.equal(await page.locator('.debug-polygon').count(), 0)
    assert.equal(await page.locator('.debug-polygon-label').count(), 0)
    assert.equal(await page.locator('.selected-hold').count(), 2)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    assert.deepEqual(errors, [])
    console.log('PASS: debug off/current/SAM2/labels/focus, mobile layout, overlay does not alter route selection or persistence')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
