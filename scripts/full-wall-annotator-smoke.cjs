const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const truth = require('../src/data/groundtruth/top_left_manual_v1.json')
async function main() {
  const base = process.env.APP_URL || 'http://127.0.0.1:8788'
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'], proxy: base.startsWith('https:') && process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY } : undefined })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, acceptDownloads: true })
    const page = await context.newPage(); page.setDefaultTimeout(30000)
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    if (process.env.ANNOTATOR_KEY_FILE) await page.goto(`${base}/auth?key=${encodeURIComponent(fs.readFileSync(process.env.ANNOTATOR_KEY_FILE, 'utf8').trim())}`)
    else await page.goto(`${base}/?annotate=1`)
    await page.getByText(/SAM2.1 Small ready/).waitFor({ timeout: 60000 })
    if (process.env.READ_ONLY_REMOTE === '1') {
      const saved = await (await context.request.get(`${base}/api/sam2/annotations`)).json()
      assert.equal(saved.holds.length, 43)
      assert.deepEqual(saved.holds, truth.holds)
      const suggestions = await (await context.request.get(`${base}/api/sam2/suggestions`)).json()
      assert.equal(suggestions.holds.length, 349)
      const response = await context.request.post(`${base}/api/sam2/predict`, { data: { points: [{ point: [.835, .69], label: 1 }], box: [.78, .62, .89, .76] } })
      assert.equal(response.status(), 200)
      const prediction = await response.json()
      assert(prediction.candidates.length > 0 && prediction.region[0] > 0 && prediction.region[1] > 0)
      await page.getByRole('button', { name: 'Review next suggestion', exact: true }).click()
      await page.locator('.annotation-preview').waitFor()
      assert.deepEqual(errors, [])
      console.log('PASS: private HTTPS full-wall UI, unchanged 43 GT holds, 349 suggestions, real bottom-right inference; no saved-data mutations')
      return
    }
    await page.getByLabel('Saved hold', { exact: true }).selectOption(truth.holds[0].id)
    await page.getByRole('button', { name: 'Edit selected', exact: true }).click()
    await page.getByText(`Editing ${truth.holds[0].id}.`, { exact: false }).waitFor()
    await page.getByRole('button', { name: 'Generate mask' }).click()
    await page.locator('.annotation-preview').waitFor()
    const acceptResponse = page.waitForResponse(r => r.url().endsWith('/accept'))
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    const after = await (await acceptResponse).json()
    assert.equal(after.holds.filter(h => h.id === truth.holds[0].id).length, 1)
    assert.equal(after.holds.length, 43)
    const edited = after.holds.find(h => h.id === truth.holds[0].id)
    const stale = await context.request.post(`${base}/api/sam2/accept`, { data: { id: truth.holds[0].id, original: { ...truth.holds[0], center: [0, 0] }, hold: truth.holds[0] } })
    assert.equal(stale.status(), 409)
    const restored = await context.request.post(`${base}/api/sam2/accept`, { data: { id: truth.holds[0].id, original: edited, hold: truth.holds[0] } })
    assert.equal(restored.status(), 200)
    // Import your existing file without duplicating the already loaded 43 IDs.
    await page.getByLabel('Import existing annotations').setInputFiles({ name: 'groundtruth.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(truth)) })
    await page.getByRole('heading', { name: 'Accepted holds (43)', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Review next suggestion', exact: true }).click()
    await page.locator('.annotation-preview').waitFor()
    await page.getByRole('button', { name: 'Skip this suggestion', exact: true }).click()
    const skipped = (await (await context.request.get(`${base}/api/sam2/annotations`)).json()).dismissed_suggestions
    assert.equal(skipped.length, 1)
    await page.reload(); await page.getByRole('heading', { name: 'Accepted holds (43)', exact: true }).waitFor()
    const suggestions = await (await context.request.get(`${base}/api/sam2/suggestions`)).json()
    assert.equal(suggestions.holds.length, 349)
    // True bottom-right prediction proves the old top-left bounds are gone.
    const full = await context.request.post(`${base}/api/sam2/predict`, { data: { points: [{ point: [.835, .69], label: 1 }], box: [.78, .62, .89, .76] } })
    assert.equal(full.status(), 200)
    const prediction = await full.json()
    assert(prediction.region[0] > 0 && prediction.region[1] > 0)
    assert(prediction.candidates.length > 0)
    assert(prediction.candidates[0].center[0] > .65 && prediction.candidates[0].center[1] > .5)
    for (const c of prediction.candidates) assert(c.polygon.length <= 16 && c.polygon.every(([x,y])=>x>=0&&x<=1&&y>=0&&y<=1))
    const invalid = await context.request.post(`${base}/api/sam2/import`, { data: { dataset: { ...truth, wallId: 'wrong-wall' } } })
    assert.equal(invalid.status(), 400)
    // Bulk-accept can be tried only on explicitly disposable test storage.
    if (process.env.DISPOSABLE_TEST_STORAGE === '1') {
      await page.getByRole('button', { name: /Accept all ≥0.95/ }).click()
      await page.waitForFunction(() => Number(document.querySelector('.annotation-library:last-child h2').textContent.match(/\d+/)[0]) > 43)
    }
    await page.getByRole('button', { name: 'Fit wall', exact: true }).click()
    await page.locator('.annotation-viewport').scrollIntoViewIfNeeded()
    fs.mkdirSync('artifacts', { recursive: true })
    await page.screenshot({ path: 'artifacts/full-wall-annotator-mobile.png' })
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth))
    assert.deepEqual(errors, [])
    console.log('PASS: 43 GT holds loaded, real refinement preserves ID, stale-save conflict, idempotent import, persistent skip, 349 suggestions, bottom-right tiled inference, mobile layout')
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
