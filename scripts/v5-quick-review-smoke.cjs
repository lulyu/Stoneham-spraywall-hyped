const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const fs=require('node:fs'),assert=require('node:assert/strict')
const base=process.env.APP_URL||'http://127.0.0.1:8791'
async function main(){
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox'],proxy:process.env.BROWSER_PROXY?{server:process.env.BROWSER_PROXY}:undefined})
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true}),page=await context.newPage(),errors=[],writes=[]
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()==='POST')writes.push(r.url())})
  if(process.env.BROWSER_FETCH_PROXY==='1')await page.route('https://**/*',async r=>r.fulfill({response:await r.fetch()}))
  if(process.env.AUTH_KEY_FILE)await page.goto(base+'/auth?key='+encodeURIComponent(fs.readFileSync(process.env.AUTH_KEY_FILE,'utf8').trim()))
  await page.goto(base+'/?review=1')
  const open=async()=>{await page.getByRole('button',{name:'Open local server scan',exact:true}).click();await page.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})}
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('stoneham-wall-review-v1:')))))
  await open()
  if(process.env.EXPECTED_VERSION)assert.equal((await state()).session.candidateVersion,process.env.EXPECTED_VERSION)
  if(process.env.EXPECTED_IMAGE_SHA256)assert.equal((await state()).session.registeredImageSha256,process.env.EXPECTED_IMAGE_SHA256)
  assert(await page.getByLabel('Reviewer name',{exact:true}).isVisible())
  const bulk=page.getByRole('button',{name:/^Confirm eligible SAM2 outlines/})
  assert(!await bulk.isDisabled());await bulk.click()
  assert(await page.getByLabel('Reviewer name',{exact:true}).evaluate(e=>document.activeElement===e))
  assert.equal((await state()).reviewRevision,0)
  const next=page.getByRole('button',{name:'Next pending hold',exact:true}),confirm=page.getByRole('button',{name:'Confirm',exact:true})
  await next.click();assert(!await confirm.isDisabled())
  assert.equal(writes.length,0,'saved suggestions load with no inference request')
  assert.equal((await state()).reviewRevision,0)
  assert((await page.getByRole('combobox',{name:'Outline candidate',exact:true}).innerText()).includes('score'))
  await confirm.click();assert.equal((await state()).reviewRevision,0)
  assert(await page.getByLabel('Reviewer name',{exact:true}).evaluate(e=>document.activeElement===e))
  await page.getByLabel('Reviewer name',{exact:true}).fill('Quick reviewer')
  assert.equal(await page.getByRole('alert').count(),0,'missing-name error clears after entry')
  const id=await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
  await page.locator('.review-quick-actions').scrollIntoViewIfNeeded()
  assert.deepEqual(await page.locator('.review-quick-buttons button').allTextContents(),['Next pending hold','Confirm','Mark removed','Mark replaced','Generate mask'])
  assert.equal(await page.getByRole('button',{name:'Zoom in',exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'Zoom out',exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'Fit wall',exact:true}).count(),1)
  const boxes=await page.locator('.review-quick-buttons button').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,width:r.width}}))
  assert(Math.abs(boxes[0].y-boxes[1].y)<1);assert(boxes[1].x>boxes[0].x+boxes[0].width)
  assert(await page.locator('.annotation-viewport').evaluate(e=>e.nextElementSibling.classList.contains('review-quick-actions')))
  assert(await page.locator('fieldset.annotation-tools').last().evaluate(e=>e.getBoundingClientRect().top>document.querySelector('.review-quick-actions').getBoundingClientRect().bottom))
  fs.mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/v5-quick-review-mobile.png'})
  await confirm.click();await page.waitForFunction(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('stoneham-wall-review-v1:')))).reviewRevision===1)
  assert.equal((await state()).entries.find(e=>e.hold.id===id).status,'verified-refined')
  await page.reload();await open();assert.equal(await page.getByLabel('Reviewer name',{exact:true}).inputValue(),'Quick reviewer')
  assert.equal((await state()).reviewRevision,1)
  await next.click()
  const removedId=await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
  await page.getByRole('button',{name:'Mark removed',exact:true}).click()
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('stoneham-wall-review-v1:')))).reviewRevision===2)
  assert.equal((await state()).entries.find(e=>e.hold.id===removedId).status,'removed')
  await next.click()
  const replacedId=await page.getByRole('combobox',{name:'Saved hold',exact:true}).inputValue()
  await page.getByRole('button',{name:'Mark replaced',exact:true}).click()
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k=>k.startsWith('stoneham-wall-review-v1:')))).reviewRevision===3)
  const replaced=await state()
  assert.equal(replaced.entries.find(e=>e.hold.id===replacedId).status,'removed')
  const added=replaced.entries.at(-1);assert.equal(added.status,'new');assert.equal(added.oldHoldId,replacedId);assert.notEqual(added.hold.id,replacedId)
  for(const width of [320,390,980]){await page.setViewportSize({width,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))}
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));assert.deepEqual(errors,[]);assert.deepEqual(writes,[])
  console.log('PASS: actionable missing reviewer, cached Next with no inference/wait, five quick actions below wall, removed/replaced identity writes, no zoom buttons, editing below, saved name/history restore, 320–980px layout.')
 }finally{await browser.close()}
}
main().catch(e=>{console.error(String(e.stack||e).replace(/([?&]key=)[A-Za-z0-9_-]+/g,'$1[redacted]'));process.exitCode=1})
