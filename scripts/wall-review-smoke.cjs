const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base=process.env.APP_URL||'http://127.0.0.1:8790'
const staticMode=process.env.STATIC_REVIEW==='1'
const folder=process.env.RESCAN_FIXTURE||'artifacts/wall-rescans/mosaic-fixture-v1'
const manifest=JSON.parse(fs.readFileSync(path.join(folder,'manifest.json')))
const key='stoneham-wall-review-v1:'+manifest.session.sessionId
const files=['manifest.json','holds_prelabels.json','review_queue.json','report.json','wall_registered.png','coverage.png','uncertainty.png','source-index-preview.png','qa-overlay.jpg'].map(name=>path.resolve(folder,name))
async function main(){
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--no-sandbox'],proxy:base.startsWith('https:')&&process.env.HTTPS_PROXY?{server:process.env.HTTPS_PROXY}:undefined})
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true})
  const page=await context.newPage(),errors=[],writes=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('request',request=>{if(request.method()==='POST')writes.push(request.url())})
  page.setDefaultTimeout(30000)
  const state=()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key)
  const revision=async n=>page.waitForFunction(({key,n})=>JSON.parse(localStorage.getItem(key))?.reviewRevision===n,{key,n})
  const open=async target=>{await target.goto(base+'/?review=1');if(staticMode)await target.getByLabel('Select scan files',{exact:true}).setInputFiles(files);else await target.getByRole('button',{name:'Open local server scan',exact:true}).click();await target.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})}
  await open(page)
  assert.equal((await state()).entries.length,677)
  assert.equal(await page.getByRole('button',{name:/Accept all/}).count(),0)
  await page.getByText('Session, reviewer & backups',{exact:true}).click()
  await page.getByRole('textbox',{name:'Reviewer name',exact:true}).fill('Mobile QA')
  await page.getByRole('button',{name:'Next pending hold',exact:true}).click()
  await page.getByRole('button',{name:'Confirm unchanged',exact:true}).click();await revision(1)
  const first=(await state()).entries[0]
  assert.equal(first.status,'verified-unchanged')
  await page.getByRole('button',{name:'Cover confirmed holds',exact:true}).click()
  await page.getByText('1 confirmed holds covered.',{exact:false}).waitFor()
  assert.equal(await page.locator('.annotation-covered').count(),1)
  await page.getByRole('button',{name:'Show original holds',exact:true}).click()
  // Select and move one vertex: refinement keeps the original ID and requires a decision.
  await page.getByRole('combobox',{name:'Saved hold',exact:true}).selectOption(first.hold.id)
  await page.getByRole('button',{name:'Edit selected',exact:true}).click()
  const handle=page.locator('.annotation-vertex').first();await handle.scrollIntoViewIfNeeded()
  const box=await handle.boundingBox();assert(box)
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
  await page.mouse.down();await page.mouse.move(box.x+box.width/2+7,box.y+box.height/2+4,{steps:4});await page.mouse.up()
  assert(await page.getByRole('button',{name:'Confirm unchanged',exact:true}).isDisabled())
  await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).click();await revision(2)
  const refined=(await state()).entries[0];assert.equal(refined.status,'verified-refined');assert.equal(refined.hold.id,first.hold.id)
  assert.notDeepEqual(refined.hold.polygon,first.hold.polygon)
  await page.getByRole('combobox',{name:'Saved hold',exact:true}).selectOption(first.hold.id)
  await page.getByRole('button',{name:'Edit selected',exact:true}).click()
  await page.getByRole('button',{name:'Old wall',exact:true}).click()
  assert(await page.getByRole('button',{name:'Confirm corrected outline',exact:true}).isDisabled())
  await page.getByRole('button',{name:'Overlay',exact:true}).click();await page.getByRole('slider',{name:'New scan opacity'}).fill('0.35')
  await page.getByRole('button',{name:'New scan',exact:true}).click()
  // Replacing at exactly the same location preserves both identities and tombstones the old one.
  await page.getByText('Different / moved hold?',{exact:true}).click()
  await page.getByRole('button',{name:'Confirm replacement with new ID',exact:true}).click();await revision(3)
  const replaced=await state();assert.equal(replaced.entries[0].status,'removed')
  const added=replaced.entries.at(-1);assert.equal(added.status,'new');assert.notEqual(added.hold.id,first.hold.id);assert.equal(added.oldHoldId,first.hold.id)
  // Capture a complete checkpoint; it must be usable without trusting its status flags.
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export progress',exact:true}).click()
  const downloaded=await downloadPromise,checkpoint=JSON.parse(fs.readFileSync(await downloaded.path(),'utf8'))
  assert.equal(checkpoint.publishable,false);assert.equal(checkpoint.reviewRevision,3)
  // A second tab opens the same state. Updating this tab must not let the old tab overwrite it.
  const other=await context.newPage();await open(other)
  await other.getByText('Session, reviewer & backups',{exact:true}).click()
  await other.getByRole('textbox',{name:'Reviewer name',exact:true}).fill('Second tab')
  await other.getByRole('button',{name:'Next pending hold',exact:true}).click();await other.getByRole('button',{name:'Confirm unchanged',exact:true}).click()
  await revision(4)
  await page.getByRole('button',{name:'Next pending hold',exact:true}).click();await page.getByRole('button',{name:'Confirm unchanged',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'Another tab changed'}).waitFor()
  assert.equal((await state()).reviewRevision,4)
  await other.close()
  // Reload reattaches the exact image and restores the latest saved history.
  await open(page);assert.equal((await state()).reviewRevision,4)
  await page.getByText('Session, reviewer & backups',{exact:true}).click()
  await page.getByRole('textbox',{name:'Reviewer name',exact:true}).fill('Mobile QA')
  await page.getByRole('button',{name:'Fit wall',exact:true}).click()
  await page.locator('.annotation-viewport').scrollIntoViewIfNeeded()
  fs.mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/wall-review-mobile.png'})
  await page.getByRole('button',{name:'Next pending hold',exact:true}).click()
  await page.locator('.annotation-vertex').first().waitFor()
  await page.locator('.annotation-viewport').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/wall-review-focused-mobile.png'})
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(writes,[]);assert.deepEqual(errors,[])
  // Browser-only import: deliberately remove all SAM2 endpoints, then resume a downloaded checkpoint.
  const standalone=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const offline=await standalone.newPage();const offlineErrors=[];offline.on('pageerror',error=>offlineErrors.push(error.message))
  await offline.route('**/api/sam2/**',route=>route.fulfill({status:404,json:{error:'No SAM2 service'}}))
  await offline.goto(base+'/?review=1')
  await offline.getByLabel('Select scan files',{exact:true}).setInputFiles(files)
  await offline.getByRole('heading',{name:'Review & annotate',exact:true}).waitFor({timeout:90000})
  await offline.getByText('Session, reviewer & backups',{exact:true}).click()
  await offline.getByLabel('Resume progress',{exact:true}).setInputFiles({name:'review-progress.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(checkpoint))})
  await offline.getByText(/revision 3$/).waitFor()
  const bad=structuredClone(checkpoint);bad.session.registeredImageSha256='f'.repeat(64)
  await offline.getByLabel('Resume progress',{exact:true}).setInputFiles({name:'wrong.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(bad))})
  await offline.getByRole('alert').filter({hasText:'Wrong scan/image identity'}).waitFor()
  assert.equal((await offline.evaluate(k=>JSON.parse(localStorage.getItem(k)),key)).reviewRevision,3)
  assert(await offline.getByRole('button',{name:'Generate mask',exact:true}).isDisabled())
  // Add a hand-drawn polygon without any inference server.
  if(!await offline.getByRole('textbox',{name:'Reviewer name',exact:true}).isVisible())await offline.getByText('Session, reviewer & backups',{exact:true}).click()
  await offline.getByRole('textbox',{name:'Reviewer name',exact:true}).fill('Offline QA')
  await offline.getByRole('button',{name:'New hold / Clear',exact:true}).click()
  await offline.getByRole('button',{name:'Draw polygon',exact:true}).click()
  await offline.getByRole('button',{name:'Fit wall',exact:true}).click()
  await offline.locator('.annotation-viewport').scrollIntoViewIfNeeded()
  const imageBox=await offline.locator('.annotation-stage image').first().boundingBox()
  for(const [x,y] of [[.45,.4],[.48,.4],[.47,.44]])await offline.touchscreen.tap(imageBox.x+x*imageBox.width,imageBox.y+y*imageBox.height)
  await offline.getByRole('button',{name:'Finish polygon',exact:true}).click()
  await offline.getByRole('button',{name:'Confirm new hold',exact:true}).click()
  await offline.waitForFunction(key=>JSON.parse(localStorage.getItem(key)).reviewRevision===4,key)
  assert.equal((await offline.evaluate(k=>JSON.parse(localStorage.getItem(k)),key)).entries.at(-1).status,'new')
  assert.deepEqual(offlineErrors,[])
  await standalone.close()
  console.log('PASS mobile: 677 pending, confirm, vertex refine, comparison lock, replacement IDs, confirmed-only cover, checkpoint export/import, reload, cross-tab conflict, wrong-image rejection, browser-only draw/save, no legacy writes, no page errors or overflow')
 }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
